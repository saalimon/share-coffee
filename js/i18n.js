// Two-language support (English default, Thai).
// t('key', {vars}) for UI strings; L({en, th}) for bilingual data values.

const KEY = 'sc.lang';
export const LANGS = ['en', 'th'];

function readStored() {
  try {
    const v = localStorage.getItem(KEY);
    return LANGS.includes(v) ? v : null;
  } catch {
    return null;
  }
}

// stored choice wins; otherwise a ?lang= hint from a shared link; otherwise English
const urlLang = new URLSearchParams(location.search).get('lang');
let lang = readStored() || (LANGS.includes(urlLang) ? urlLang : 'en');
document.documentElement.lang = lang;

export const getLang = () => lang;
export const locale = () => (lang === 'th' ? 'th-TH' : 'en-US');

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* noop */ }
  document.documentElement.lang = next;
  window.dispatchEvent(new CustomEvent('lang:changed', { detail: next }));
}

/** Pick the current language from a bilingual value; plain values pass through. */
export function L(v) {
  if (v && typeof v === 'object' && !Array.isArray(v) && ('en' in v || 'th' in v)) return v[lang] ?? v.en ?? v.th;
  return v;
}

export function t(key, vars) {
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

